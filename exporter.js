/* PixelProTech Pixel App — exporter.js
   Generates a real, editor-independent website as a FLAT set of files (HTML pages, site.css, site.js, assets),
   verifies every local reference before reporting success, and packs the result into a flat ZIP. */
(function () {
  'use strict';
  const PX = (window.PX = window.PX || {});
  const esc = PX.esc;

  const SITE_JS = `/* Generated by PixelProTech Pixel App. Marks the current page in the navigation. */
(function () {
  'use strict';
  var file = location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.px-nav-links a, .px-brand').forEach(function (a) {
    var h = (a.getAttribute('href') || '').split('#')[0];
    if (h && h === file && a.classList.contains('px-brand') === false) a.setAttribute('aria-current', 'page');
  });
  document.querySelectorAll('.px-nav-links a').forEach(function (a) {
    a.addEventListener('click', function () { var c = a.closest('.px-nav-in').querySelector('.px-nav-check'); if (c) c.checked = false; });
  });
})();
`;

  const EXT = { 'image/png': 'png', 'image/jpeg': 'jpg', 'image/webp': 'webp', 'image/gif': 'gif', 'image/svg+xml': 'svg', 'image/avif': 'avif' };
  const safeName = (s) => String(s || 'file').toLowerCase().replace(/[^a-z0-9._-]+/g, '-').replace(/^[-.]+|[-]+$/g, '') || 'file';

  function dataUrlToBytes(u) {
    const m = /^data:([^;,]*)(;base64)?,(.*)$/s.exec(u || '');
    if (!m) throw new Error('Asset has no readable data');
    if (m[2]) { const bin = atob(m[3]); const b = new Uint8Array(bin.length); for (let i = 0; i < bin.length; i++) b[i] = bin.charCodeAt(i); return b; }
    return new TextEncoder().encode(decodeURIComponent(m[3]));
  }

  function usedAssetIds(project) {
    const ids = new Set();
    project.pages.forEach((p) => p.nodes.forEach((n) => PX.assetRefs(n).forEach((r) => ids.add(r.id))));
    return ids;
  }

  function pageDoc(project, page, ctx, css, inline) {
    const lang = esc((project.settings && project.settings.lang) || 'en');
    const desc = project.settings && project.settings.description ? `<meta name="description" content="${esc(project.settings.description)}">` : '';
    const head = inline
      ? `<style>${css}</style>`
      : `<link rel="stylesheet" href="site.css"><script src="site.js" defer></script>`;
    return `<!doctype html>\n<html lang="${lang}">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1">\n<title>${esc(page.title)}</title>\n${desc}\n${head}\n</head>\n<body>\n${PX.renderNodes(page.nodes, ctx)}\n</body>\n</html>\n`;
  }

  /* Build the file set. Returns { ok, files, errors, warnings }. Never throws for project problems. */
  function build(project, assets) {
    const files = [], errors = [], warnings = [];
    const assetFile = {}; let k = 0;
    try {
      usedAssetIds(project).forEach((id) => {
        const a = assets[id];
        if (!a || !a.dataUrl) { warnings.push(`Asset "${id}" is referenced but missing; the image slot is exported empty.`); return; }
        let name = safeName(a.name); const ext = EXT[a.mime];
        if (ext && !name.endsWith('.' + ext)) name = name.replace(/\.[a-z0-9]+$/, '') + '.' + ext;
        const fname = `asset-${++k}-${name}`;
        try { files.push({ name: fname, bytes: dataUrlToBytes(a.dataUrl), type: a.mime || 'application/octet-stream' }); assetFile[id] = fname; }
        catch (e) { errors.push(`Asset "${a.name}" could not be decoded: ${e.message}`); }
      });
      const ctx = { edit: false, project, assetUrl: (id) => assetFile[id] || '' };
      const css = PX.buildCss(project, ctx);
      project.pages.forEach((p, i) => {
        const fname = i === 0 ? 'index.html' : `${p.slug}.html`;
        files.push({ name: fname, text: pageDoc(project, p, ctx, css, false), type: 'text/html' });
      });
      files.push({ name: 'site.css', text: css, type: 'text/css' });
      files.push({ name: 'site.js', text: SITE_JS, type: 'text/javascript' });
    } catch (e) { errors.push('Generation failed: ' + (e && e.message || e)); }
    return { ok: errors.length === 0, files, errors, warnings };
  }

  /* Self-contained single-page document for measuring/previewing (CSS inline, assets as data URLs). */
  function renderPageInline(project, assets, page) {
    const ctx = { edit: false, project, assetUrl: (id) => (assets[id] && assets[id].dataUrl) || '' };
    return pageDoc(project, page, ctx, PX.buildCss(project, ctx), true);
  }

  const isExternal = (u) => /^([a-z][a-z0-9+.-]*:|\/\/)/i.test(u);
  function verify(files) {
    const problems = []; const names = new Set(files.map((f) => f.name));
    ['index.html', 'site.css', 'site.js'].forEach((r) => { if (!names.has(r)) problems.push({ file: r, message: `Required file ${r} is missing from the export.` }); });
    const text = (f) => (f.text != null ? f.text : '');
    files.forEach((f) => {
      const size = f.bytes ? f.bytes.length : new TextEncoder().encode(f.text || '').length;
      if (!size) problems.push({ file: f.name, message: 'File is empty.' });
      if (/[\\/]/.test(f.name) || /^\./.test(f.name)) problems.push({ file: f.name, message: 'File name is not a flat root-level name.' });
    });
    const ids = {};
    const docs = {};
    files.filter((f) => f.name.endsWith('.html')).forEach((f) => {
      const d = new DOMParser().parseFromString(text(f), 'text/html'); docs[f.name] = d;
      ids[f.name] = new Set([...d.querySelectorAll('[id]')].map((e) => e.id));
    });
    Object.keys(docs).forEach((fn) => {
      const d = docs[fn];
      d.querySelectorAll('a[href],link[href],script[src],img[src]').forEach((el) => {
        const attr = el.hasAttribute('href') ? 'href' : 'src'; const v = (el.getAttribute(attr) || '').trim();
        const where = `${fn}: <${el.tagName.toLowerCase()} ${attr}="${v}">`;
        if (v === '' || v === '#') { problems.push({ file: fn, message: `${where} has no real target.` }); return; }
        if (v[0] === '#') { if (!ids[fn].has(v.slice(1))) problems.push({ file: fn, message: `${where} points to an anchor that does not exist on this page.` }); return; }
        if (isExternal(v)) return;
        if (v[0] === '/' || v.startsWith('../') || v.includes('\\')) { problems.push({ file: fn, message: `${where} uses a non-flat path.` }); return; }
        const [pathPart, hash] = v.split('#'); const p = pathPart.split('?')[0];
        if (!names.has(p)) { problems.push({ file: fn, message: `${where} points to a file that is not in the export.` }); return; }
        if (hash && docs[p] && !ids[p].has(hash)) problems.push({ file: fn, message: `${where} points to an anchor missing in ${p}.` });
      });
    });
    files.filter((f) => f.name.endsWith('.css')).forEach((f) => {
      const re = /url\(\s*["']?([^"')]+)["']?\s*\)/g; let m;
      while ((m = re.exec(text(f)))) { const u = m[1]; if (u.startsWith('data:') || isExternal(u)) continue; if (!names.has(u)) problems.push({ file: f.name, message: `CSS url(${u}) points to a file that is not in the export.` }); }
    });
    return { ok: problems.length === 0, problems };
  }

  /* ---- ZIP (stored, flat) ---- */
  let crcTable = null;
  function crc32(b) {
    if (!crcTable) { crcTable = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; crcTable[n] = c >>> 0; } }
    let c = 0xffffffff; for (let i = 0; i < b.length; i++) c = crcTable[(c ^ b[i]) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0;
  }
  function zip(files) {
    const enc = new TextEncoder(); const parts = [], central = []; let offset = 0;
    const d = new Date(); const time = (d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1); const date = (((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate());
    files.forEach((f) => {
      const name = enc.encode(f.name); const data = f.bytes || enc.encode(f.text || ''); const crc = crc32(data);
      const lh = new DataView(new ArrayBuffer(30));
      lh.setUint32(0, 0x04034b50, true); lh.setUint16(4, 20, true); lh.setUint16(6, 0x0800, true); lh.setUint16(8, 0, true); lh.setUint16(10, time, true); lh.setUint16(12, date, true);
      lh.setUint32(14, crc, true); lh.setUint32(18, data.length, true); lh.setUint32(22, data.length, true); lh.setUint16(26, name.length, true); lh.setUint16(28, 0, true);
      parts.push(new Uint8Array(lh.buffer), name, data);
      const ch = new DataView(new ArrayBuffer(46));
      ch.setUint32(0, 0x02014b50, true); ch.setUint16(4, 20, true); ch.setUint16(6, 20, true); ch.setUint16(8, 0x0800, true); ch.setUint16(10, 0, true); ch.setUint16(12, time, true); ch.setUint16(14, date, true);
      ch.setUint32(16, crc, true); ch.setUint32(20, data.length, true); ch.setUint32(24, data.length, true); ch.setUint16(28, name.length, true); ch.setUint32(42, offset, true);
      central.push(new Uint8Array(ch.buffer), name);
      offset += 30 + name.length + data.length;
    });
    const cdSize = central.reduce((a, p) => a + p.length, 0);
    const end = new DataView(new ArrayBuffer(22)); end.setUint32(0, 0x06054b50, true); end.setUint16(8, files.length, true); end.setUint16(10, files.length, true); end.setUint32(12, cdSize, true); end.setUint32(16, offset, true);
    return new Blob([...parts, ...central, new Uint8Array(end.buffer)], { type: 'application/zip' });
  }

  /* Full pipeline: build → verify → zip. Reports success only when every step passed. */
  function exportSite(project, assets) {
    const b = build(project, assets);
    if (!b.ok) return { ok: false, stage: 'generate', errors: b.errors, warnings: b.warnings };
    const v = verify(b.files);
    if (!v.ok) return { ok: false, stage: 'verify', errors: v.problems.map((p) => p.message), problems: v.problems, warnings: b.warnings, files: b.files };
    const warnings = b.warnings.slice();
    b.files.filter((f) => f.name.endsWith('.html')).forEach((f) => {
      const dead = new DOMParser().parseFromString(f.text, 'text/html').querySelectorAll('a:not([href])').length;
      if (dead) warnings.push(`${f.name} has ${dead} link${dead === 1 ? '' : 's'} with no target (exported as non-clickable text). Pixel Preflight lists them.`);
    });
    let blob; try { blob = zip(b.files); } catch (e) { return { ok: false, stage: 'package', errors: ['Packaging failed: ' + e.message], warnings }; }
    return { ok: true, blob, files: b.files.map((f) => ({ name: f.name, size: f.bytes ? f.bytes.length : new TextEncoder().encode(f.text).length })), warnings, filesFull: b.files };
  }
  function download(blob, name) {
    const a = document.createElement('a'); const u = URL.createObjectURL(blob); a.href = u; a.download = name; document.body.appendChild(a); a.click(); a.remove(); setTimeout(() => URL.revokeObjectURL(u), 4000);
  }

  PX.Exporter = { build, verify, zip, exportSite, download, renderPageInline, crc32, safeName };
})();
